import { Router } from 'express';
import { authenticate } from '../../middlewares/auth.js';
import { validate } from '../../middlewares/validate.js';
import { tryCatch } from '../../utils/tryCatch.js';
import { interactionController as c } from './interactions.controller.js';
import { interactionSchemas as s } from './interactions.validation.js';
const r=Router();
r.use((_req,res,next)=>{res.set('Cache-Control','no-store');next();});
r.get('/conversations',authenticate,validate(s.page),tryCatch(c.conversations));
r.post('/conversations',authenticate,validate(s.start),tryCatch(c.startConversation));
r.get('/conversations/:id',authenticate,validate(s.id),tryCatch(c.conversation));
r.get('/conversations/:id/messages',authenticate,validate(s.messages),tryCatch(c.messages));
r.post('/conversations/:id/messages',authenticate,validate(s.message),tryCatch(c.sendMessage));
r.delete('/conversations/:id/messages/:messageId',authenticate,validate(s.messageId),tryCatch(c.deleteMessage));
r.post('/conversations/:id/messages/:messageId/restore',authenticate,validate(s.messageId),tryCatch(c.restoreMessage));
r.delete('/conversations/:id',authenticate,validate(s.id),tryCatch(c.deleteConversation));
r.post('/conversations/:id/restore',authenticate,validate(s.id),tryCatch(c.restoreConversation));
r.post('/service-requests',authenticate,validate(s.createRequest),tryCatch(c.createRequest));
r.get('/service-requests',authenticate,validate(s.requests),tryCatch(c.requests));
r.get('/service-requests/:id',authenticate,validate(s.id),tryCatch(c.request));
r.patch('/service-requests/:id',authenticate,validate(s.updateRequest),tryCatch(c.updateRequest));
r.get('/service-requests/:id/events',authenticate,validate(s.events),tryCatch(c.events));
r.delete('/service-requests/:id',authenticate,validate(s.id),tryCatch(c.deleteRequest));
r.post('/service-requests/:id/restore',authenticate,validate(s.id),tryCatch(c.restoreRequest));
r.get('/workers/:id/reviews',authenticate,validate(s.reviews),tryCatch(c.reviews));
r.post('/workers/:id/reviews',authenticate,validate(s.addReview),tryCatch(c.addReview));
r.get('/me/reviews',authenticate,validate(s.page),tryCatch(c.myReviews));
r.patch('/reviews/:id',authenticate,validate(s.editReview),tryCatch(c.editReview));
r.delete('/reviews/:id',authenticate,validate(s.id),tryCatch(c.deleteReview));
r.post('/reviews/:id/restore',authenticate,validate(s.id),tryCatch(c.restoreReview));
export default r;
