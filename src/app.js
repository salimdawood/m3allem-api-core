import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import pinoHttp from 'pino-http';
import { randomUUID } from 'node:crypto';
import { env } from './config/env.js';
import authRoutes from './modules/auth/auth.routes.js';
import catalogRoutes from './modules/catalog/catalog.routes.js';
import { errorHandler, notFound } from './middlewares/error.js';
import accountRoutes from './modules/account/account.routes.js';
import workerRoutes from './modules/workers/worker.routes.js';
import interactionRoutes from './modules/interactions/interactions.routes.js';
import authMeRoutes from './modules/auth/auth.me.routes.js';
import uploadRoutes from './modules/uploads/upload.routes.js';
import verificationRoutes from './modules/verification/verification.routes.js';
import healthRoutes from './modules/health/health.routes.js';
import { requestTimeout } from './middlewares/timeout.js';
import { AppError } from './utils/AppError.js';
import { logger } from './config/logger.js';
import { apiRateLimit } from './middlewares/rate-limit.js';
import { jsonReplacer } from './utils/id.js';

export const app = express();
app.set('json replacer', jsonReplacer);
app.disable('x-powered-by');
app.set('trust proxy',env.TRUST_PROXY_HOPS);
app.use(helmet());
app.use(cors({ origin: env.CORS_ALLOWED_ORIGINS ? env.CORS_ALLOWED_ORIGINS.split(',').map((x) => x.trim()) : false }));
app.use(pinoHttp({ logger, genReqId: (req) => {
  const incoming=req.get('x-request-id');
  return incoming&&/^[a-zA-Z0-9._-]{1,100}$/.test(incoming)?incoming:randomUUID();
}, serializers:{req:(req)=>({id:req.id,method:req.method,url:req.route?.path?`${req.baseUrl??''}${req.route.path}`:'<unmatched>',remoteAddress:req.socket?.remoteAddress,userAgent:req.headers['user-agent']})},customProps:(req)=>req.user?.id?{userId:req.user.id}:{}, redact: ['req.headers.authorization', 'req.headers.cookie'], autoLogging:{ignore:(req)=>req.url?.startsWith('/health/')} }));
app.use(express.json({ limit: '1mb' }));
app.use(requestTimeout(env.REQUEST_TIMEOUT_MS));
app.use((req,_res,next)=>{
  if(env.APP_ENV==='production'&&!req.secure)return next(new AppError('HTTPS_REQUIRED',400));
  next();
});
app.use(healthRoutes);
app.use(apiRateLimit);
app.use('/v1/auth', authRoutes);
app.use('/v1/catalog', catalogRoutes);
app.use('/v1', accountRoutes);
app.use('/v1', authMeRoutes);
app.use('/v1', workerRoutes);
app.use('/v1', interactionRoutes);
app.use('/v1/uploads', uploadRoutes);
app.use('/v1', verificationRoutes);
app.use(notFound);
app.use(errorHandler);
